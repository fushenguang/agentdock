#!/usr/bin/env node
// gen-skill-docs.mjs — regenerates apps/docs/content/docs/skills/*.mdx + meta.json from
// skills.json. Design.md §6: skill directory index is a generated docs page, not an
// independent browsing UI, so this is the only place that renders a skill's manifest entry
// into human-readable form.
//
// Deterministic and pure: given the same skills.json, always produces the same output bytes
// (sorted by id, no timestamps in the rendered page — publishedAt is a manifest-only field).
// This determinism is what lets gate ② (scripts/gates/manifest-fresh.mjs) diff the generated
// files against what's on disk without a normalization step.
//
// Usage:
//   node scripts/gen-skill-docs.mjs           # writes apps/docs/content/docs/skills/*
// Imported by scripts/gates/manifest-fresh.mjs for the read-only freshness comparison.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const DOCS_SKILLS_DIR_REL = 'apps/docs/content/docs/skills'

function escapeYamlString(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')
}

function renderSkillMdx(entry) {
  const title = escapeYamlString(entry.name)
  const description = escapeYamlString(entry.description)
  const lines = [
    '---',
    `title: "${title}"`,
    `description: "${description}"`,
    '---',
    '',
    "{/* GENERATED by scripts/gen-skill-docs.mjs from skills.json. Do not edit by hand — edit the skill's SKILL.md and run `pnpm skills:sync`. */}",
    '',
    `- **id**: \`${entry.id}\``,
    `- **source**: \`${entry.source}\``,
  ]
  if (entry.path) lines.push(`- **path**: \`${entry.path}\``)
  if (entry.license) lines.push(`- **license**: \`${entry.license}\``)
  lines.push('')
  return lines.join('\n')
}

function renderMetaJson(sortedIds) {
  return JSON.stringify({ title: 'Skills', pages: sortedIds }, null, 2) + '\n'
}

/**
 * Pure function: manifest -> { relPath: content } for every generated docs file.
 * relPath is relative to the repo root (e.g. "apps/docs/content/docs/skills/example-skill.mdx").
 */
export function buildDocsFiles(manifest) {
  const skills = [...(manifest.skills ?? [])].sort((a, b) => a.id.localeCompare(b.id))
  const files = new Map()

  for (const entry of skills) {
    files.set(`${DOCS_SKILLS_DIR_REL}/${entry.id}.mdx`, renderSkillMdx(entry))
  }
  files.set(`${DOCS_SKILLS_DIR_REL}/meta.json`, renderMetaJson(skills.map((s) => s.id)))

  return files
}

/** Reads the current contents of the generated docs dir, same shape as buildDocsFiles(). */
export function readExistingDocsFiles(repoRoot) {
  const dirAbs = join(repoRoot, DOCS_SKILLS_DIR_REL)
  const files = new Map()
  if (!existsSync(dirAbs)) return files

  for (const name of readdirSync(dirAbs)) {
    if (name === '.gitkeep') continue
    const relPath = `${DOCS_SKILLS_DIR_REL}/${name}`
    files.set(relPath, readFileSync(join(dirAbs, name), 'utf-8'))
  }
  return files
}

function writeDocsFiles(repoRoot, files) {
  const dirAbs = join(repoRoot, DOCS_SKILLS_DIR_REL)
  if (existsSync(dirAbs)) {
    rmSync(dirAbs, { recursive: true, force: true })
  }
  mkdirSync(dirAbs, { recursive: true })
  for (const [relPath, content] of files) {
    writeFileSync(join(repoRoot, relPath), content, 'utf-8')
  }
}

function main() {
  const repoRoot = process.cwd()
  const manifestPath = join(repoRoot, 'skills.json')
  if (!existsSync(manifestPath)) {
    console.error(`gen-skill-docs: no skills.json found at ${manifestPath}`)
    process.exit(1)
  }
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf-8'))
  const files = buildDocsFiles(manifest)
  writeDocsFiles(repoRoot, files)
  console.log(`gen-skill-docs: wrote ${files.size} file(s) to ${DOCS_SKILLS_DIR_REL}/`)
}

const isMain = process.argv[1] === fileURLToPath(import.meta.url)
if (isMain) {
  main()
}
