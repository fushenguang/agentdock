import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const runtimeRoot = dirname(fileURLToPath(import.meta.url));
const runtimeSource = join(runtimeRoot, "create-hosted-runtime.mjs");
const vaultSupplySource = join(runtimeRoot, "vault-supply.mjs");
const serverEntrySource = join(runtimeRoot, "package-server.mjs");
const assembleSource = join(runtimeRoot, "assemble.mjs");
const webChannelClientSource = join(runtimeRoot, "web-channel-client.ts");
const capabilityServiceSkeletonSource = join(runtimeRoot, "capability-service-skeleton.ts");

function assertDirectory(path, label) {
  if (!existsSync(path)) throw new Error(`${label} does not exist: ${path}`);
}

export function copyHostedRuntimeOutputs({ outputRoot, configSource } = {}) {
  if (!outputRoot) throw new Error("outputRoot is required");
  const serverRoot = join(outputRoot, "runtime", "server");
  mkdirSync(serverRoot, { recursive: true });
  cpSync(runtimeSource, join(serverRoot, "hosted-runtime.mjs"));
  // hosted-runtime.mjs imports the vault supply chain (spec 0.8.0) — the
  // packaged bundle must ship both files or the import breaks at runtime.
  cpSync(vaultSupplySource, join(serverRoot, "vault-supply.mjs"));
  cpSync(serverEntrySource, join(outputRoot, "server.mjs"));
  if (configSource) {
    const configTarget = join(outputRoot, "runtime", "hosted-runtime-config.mjs");
    mkdirSync(dirname(configTarget), { recursive: true });
    cpSync(configSource, configTarget);
  }
  return {
    runtimePath: join(serverRoot, "hosted-runtime.mjs"),
    vaultSupplyPath: join(serverRoot, "vault-supply.mjs"),
    serverEntryPath: join(outputRoot, "server.mjs"),
  };
}

export function writeHostedRuntimeShim({ appRoot }) {
  if (!appRoot) throw new Error("appRoot is required");
  const shimRoot = join(appRoot, "src", "server");
  mkdirSync(shimRoot, { recursive: true });
  const shimPath = join(shimRoot, "hosted-runtime.mjs");
  const standardsPath = relative(shimRoot, runtimeSource).split("\\").join("/");
  const source = [
    "// Generated by pnpm init:web from standards/web-scaffold/hosted-runtime/create-hosted-runtime.mjs.",
    "// The packaged build replaces this shim with the same private runtime implementation.",
    `export * from ${JSON.stringify(standardsPath)};`,
    "",
  ].join("\n");
  writeFileSync(shimPath, source);
  return shimPath;
}

/**
 * WS-8: the page half of the Web Channel is injected from the standard source, not forked per
 * package. The generated header keeps the provenance visible where the bundle cannot.
 */
export function writeStandardWebChannelClient({ appRoot } = {}) {
  if (!appRoot) throw new Error("appRoot is required");
  const targetRoot = join(appRoot, "src", "agent");
  mkdirSync(targetRoot, { recursive: true });
  const target = join(targetRoot, "web-channel-client.ts");
  const source = readFileSync(webChannelClientSource, "utf8");
  writeFileSync(
    target,
    `// Generated by pnpm init:web from standards/web-scaffold/hosted-runtime/web-channel-client.ts.\n${source}`,
  );
  return target;
}

/**
 * WS-7.3: every scaffolded package Web starts with a runnable capability service entry, so the
 * packaged build always bundles the server-side execution path. Never overwrite an existing
 * implementation — injection happens once, at scaffold time.
 */
export function writeCapabilityServiceSkeleton({ appRoot } = {}) {
  if (!appRoot) throw new Error("appRoot is required");
  const targetRoot = join(appRoot, "src", "server");
  mkdirSync(targetRoot, { recursive: true });
  const target = join(targetRoot, "capability-service.ts");
  if (existsSync(target)) return { target, created: false };
  const source = readFileSync(capabilityServiceSkeletonSource, "utf8");
  writeFileSync(
    target,
    `// Generated by pnpm init:web from standards/web-scaffold/hosted-runtime/capability-service-skeleton.ts.\n${source}`,
  );
  return { target, created: true };
}

export function renderStandardBuildScript({ appRoot, packageId } = {}) {
  if (!appRoot || !packageId) throw new Error("appRoot and packageId are required");
  const scriptsRoot = join(appRoot, "scripts");
  const assembleImport = relative(scriptsRoot, assembleSource).split("\\").join("/");
  return `import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import {
  buildCapabilityService,
  copyHostedRuntimeOutputs,
} from ${JSON.stringify(assembleImport)};

const appRoot = resolve(import.meta.dirname, "..");
const repoRoot = resolve(appRoot, "..", "..");
const packageId = ${JSON.stringify(packageId)};
const packageRoot = join(repoRoot, packageId);
const outputRoot = join(packageRoot, "web");
const pnpm = process.platform === "win32" ? "pnpm.cmd" : "pnpm";

const build = spawnSync(pnpm, ["build"], { cwd: appRoot, stdio: "inherit" });
if (build.error) throw build.error;
if (build.status !== 0) process.exit(build.status ?? 1);

rmSync(outputRoot, { recursive: true, force: true });
mkdirSync(outputRoot, { recursive: true });
cpSync(join(appRoot, "dist", "client"), join(outputRoot, "client"), { recursive: true });
cpSync(join(appRoot, "dist", "server"), join(outputRoot, "server"), { recursive: true });

const capabilityEntry = join(appRoot, "src", "server", "capability-service.ts");
if (existsSync(capabilityEntry)) {
  await buildCapabilityService({ appRoot, entry: capabilityEntry, outputRoot });
}
copyHostedRuntimeOutputs({ outputRoot });

const packageJson = JSON.parse(readFileSync(join(packageRoot, "package.json"), "utf8"));
const contract = JSON.parse(readFileSync(join(packageRoot, "contract.json"), "utf8"));
writeFileSync(
  join(outputRoot, "package.json"),
  \`\${JSON.stringify({ private: true, type: "module" }, null, 2)}\\n\`,
);
writeFileSync(
  join(outputRoot, "build.json"),
  \`\${JSON.stringify(
    {
      packageId,
      packageVersion: packageJson.version,
      source: "apps/" + packageId + "-web",
      entry: "server.mjs",
      specVersion: contract.constraints.specVersion,
      protocolVersion: contract.constraints.protocolVersion,
      contentVersion: contract.constraints.contentVersion,
      webApiVersion: "1.0.0",
      apiVersion: "1.0.0",
    },
    null,
    2,
  )}\\n\`,
);
console.log(\`[\${packageId}-web] packaged hosted runtime into \${outputRoot}\`);
`;
}

export function injectHostedRuntime({ appRoot, packageId } = {}) {
  if (!appRoot || !packageId) throw new Error("appRoot and packageId are required");
  assertDirectory(join(appRoot, "src"), "web source directory");
  const shimPath = writeHostedRuntimeShim({ appRoot });
  const webChannelClientPath = writeStandardWebChannelClient({ appRoot });
  const { target: capabilityServicePath } = writeCapabilityServiceSkeleton({ appRoot });
  const scriptsRoot = join(appRoot, "scripts");
  mkdirSync(scriptsRoot, { recursive: true });
  const buildScriptPath = join(scriptsRoot, "build-domain-package.mjs");
  writeFileSync(buildScriptPath, renderStandardBuildScript({ appRoot, packageId }));
  return { shimPath, webChannelClientPath, capabilityServicePath, buildScriptPath };
}

export async function buildCapabilityService({
  appRoot,
  entry,
  outputRoot,
  // native/二进制类模块保持 external（运行时从 web/node_modules/ 解析）：
  // ffprobe-static 的 CJS index.js 以 __dirname 相对定位二进制，bundle 进
  // ESM 产物会在启动即炸 ReferenceError（promo-video 0.5.10 真机实锤）。
  external = ["better-sqlite3", "ffmpeg-static", "ffprobe-static"],
} = {}) {
  if (!appRoot || !entry || !outputRoot) {
    throw new Error("appRoot, entry and outputRoot are required");
  }
  const absoluteEntry = resolve(appRoot, entry);
  assertDirectory(absoluteEntry, "capability service entry");
  const temporaryOutput = join(appRoot, "dist", "hosted-capability-service");
  const resolvedAppRoot = resolve(appRoot);
  const appRequire = createRequire(join(resolvedAppRoot, "package.json"));
  const viteEntry = appRequire.resolve("vite");
  const { build } = await import(pathToFileURL(viteEntry).href);
  await build({
    configFile: false,
    root: appRoot,
    resolve: { alias: { "@": join(appRoot, "src") } },
    ssr: { noExternal: true, external },
    build: {
      ssr: absoluteEntry,
      outDir: temporaryOutput,
      emptyOutDir: true,
      minify: false,
      rollupOptions: {
        output: {
          format: "es",
          entryFileNames: "assets/capability-service.mjs",
        },
      },
    },
  });
  const builtEntry = join(temporaryOutput, "assets", "capability-service.mjs");
  assertDirectory(builtEntry, "built capability service");
  const target = join(outputRoot, "server", "assets", "capability-service.mjs");
  mkdirSync(dirname(target), { recursive: true });
  cpSync(builtEntry, target);
  return target;
}
